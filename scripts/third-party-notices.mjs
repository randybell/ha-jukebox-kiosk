  out.push('the integration at `custom_components/jukebox_kiosk/www/`. It covers the third-party code');
  out.push('bundled into `jukebox-card.js`. Their license comments are also kept in the minified bundle.');
  out.push('');
  out.push('## Credits and inspiration');
  out.push('');
  out.push('No code from the projects below is copied into this repository unless listed under "Bundled" further down.');
  out.push('');
  out.push('- **Music Assistant** (https://music-assistant.io): the music server this integration talks to, through the');
  out.push('  `music-assistant-client` library that Home Assistant\'s Music Assistant integration already installs.');
  out.push('- **Home Assistant** (https://www.home-assistant.io): the platform, its WebSocket API, and the core');
  out.push('  `music_assistant` integration whose config entry and client this integration reuses.');
  out.push('- **LRCLIB** (https://lrclib.net): free synced lyrics, fetched by Music Assistant\'s lyrics provider.');
  out.push('- **mass_queue** (Music Assistant Queue Actions, a HACS integration): the earlier way this card reached the');
  out.push('  Music Assistant queue and track lists. Its service set inspired the jukebox_kiosk WebSocket API; it is still');
  out.push('  supported as the card\'s legacy `mass_queue` backend.');
  out.push('- **Kiosk MA Cards**: inspiration for a touch-first Music Assistant kiosk on a wall tablet.');
  out.push('');
  out.push('## Bundled into jukebox-card.js');
  out.push('');
  out.push('| Package | Version | License |');
  out.push('| --- | --- | --- |');
  for (const p of pkgs) out.push(`| ${p.name} | ${p.version} | ${p.license} |`);
  out.push('');
  for (const p of pkgs) {
    out.push(`### ${p.name} ${p.version}`);
    out.push('');
    out.push(`License: ${p.license}${p.homepage ? `  \nHomepage: ${p.homepage}` : ''}`);
    out.push('');
    out.push(fence(p.text));
    out.push('');
  }
  out.push('## Icons in jukebox-card.js');
  out.push('');
  out.push('The SVG path data in `src/icons.ts` (play, pause, search, queue, volume, heart and the other UI glyphs) comes');
